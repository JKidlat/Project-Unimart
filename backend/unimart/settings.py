# Database
# https://docs.djangoproject.com/en/5.2/ref/settings/#databases
# Automatically connects to PostgreSQL / Supabase when DATABASE_URL is present,
# otherwise falls back seamlessly to SQLite for local development.

import urllib.parse

database_url = os.environ.get('DATABASE_URL')
if database_url and not database_url.startswith('sqlite'):
    url = urllib.parse.urlparse(database_url)
    query_params = urllib.parse.parse_qs(url.query)
    ssl_mode = query_params.get('sslmode', ['require'])[0]
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.postgresql',
            'NAME': urllib.parse.unquote(url.path[1:]) if url.path else 'postgres',
            'USER': urllib.parse.unquote(url.username) if url.username else '',
            'PASSWORD': urllib.parse.unquote(url.password) if url.password else '',
            'HOST': url.hostname,
            'PORT': url.port or 5432,
            'OPTIONS': {
                'sslmode': ssl_mode,
            },
        }
    }
else:
    DATABASES = {
        'default': {
            'ENGINE': 'django.db.backends.sqlite3',
            'NAME': BASE_DIR / 'db.sqlite3',
        }
    }


